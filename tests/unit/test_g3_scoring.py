@_needs_bbw
def test_g3_not_asked_is_in_coverage_but_out_of_missed_evidence():
    """D37 ruling 3, the asymmetry. Asserted on a synthetic row rather than the
    real run, which currently has no NOT_ASKED field."""
    s = score_anchor("drf", _BBW)
    headline = [r for r in s.rows if r.outcome not in EXCLUDED_OUTCOMES]
    shipped = [r for r in headline if r.outcome in SHIPPED_OUTCOMES]
    assert len(shipped) == 4 and len(headline) == 44        # coverage 4/44
    # NOT_ASKED never counts as missed evidence
    assert all(not r.is_missed_evidence for r in s.rows if r.outcome is Outcome.NOT_ASKED)


