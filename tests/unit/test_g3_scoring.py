# --- trap guards -------------------------------------------------------------

def test_g3_runfield_does_not_expose_the_agreement_bit():
    """form_filler sets trace agreement to (tag == "STATED"), which is NOT model
    concord. RunField must not carry it at all."""
    import dataclasses

    names = {f.name for f in dataclasses.fields(RunField)}
    assert "agreement" not in names
    assert "models_agree" in {p for p in dir(RunField)}


@_needs_bbw
def test_g3_models_agree_genuinely_differs_from_the_trace_bit():
    """The behavioural half of the guard. On the real BBW run there are fields
    where both models agreed but the quote gate failed: the trace bit says False
    while true concord is True. If anyone "simplifies" the scorer back to reading
    trace["agreement"], this fails."""
    import json

    art = load_run(_BBW)
    raw = {r["field"]: r for r in json.loads((_BBW / "trace_0.json").read_text())["records"]}
    divergent = [name for name, f in art.fields.items() if raw[name]["agreement"] != f.models_agree]
    assert divergent, "expected at least one field where the trace bit != true agreement"
    # and at least one of them is the agree-but-gate-failed population
    assert any("agree_quote_gate_failed" in art.fields[n].conditions for n in divergent)


@_needs_bbw
def test_g3_conditions_are_incidence_not_a_partition():
    """The ordered D9 merge attributes each field to ONE reason (quote gate before
    single-response), so the shipped reason under-counts one-model-mute fields.
    conditions is the order-free view; the two must genuinely disagree, or the
    metrics layer would be reporting one number twice."""
    art = load_run(_BBW)
    one_silent = sum(1 for f in art.fields.values() if "one_silent" in f.conditions)
    labelled = sum(1 for f in art.fields.values() if f.shipped_reason == "single_response")
    assert one_silent > labelled


@_needs_bbw
def test_g3_trace_integrity_is_verified_on_load():
    """load_run proves dict traversal read exactly the bytes the spec header
    hashed (D12). Corrupting the trace must be caught."""
    import copy
    import json

    from evaluation.harness.run_artefacts import verify_trace_integrity

    spec = json.loads((_BBW / "spec_0.json").read_text())
    trace = json.loads((_BBW / "trace_0.json").read_text())
