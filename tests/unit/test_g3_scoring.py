def test_g3_unnormalisable_gold_is_not_scorable_rather_than_wrong():
    """D37 ruling 2: gold hac_lags = "floor(T^0.25)" is a faithful transcription
    into a field type that cannot hold it. Neither correct nor wrong."""
    out = compare_field(FieldKey("hac_lags"), "floor(T^0.25)", 4)
    assert out.comparability is Comparability.GOLD_UNNORMALISABLE
    assert out.equal is None
    # the wrapper is what protects us -- normalise itself still raises
    from agents.librarian.errors import LibrarianSchemaError
    from agents.librarian.pipeline.form_filler import normalise

    with pytest.raises(LibrarianSchemaError):
        normalise("hac_lags", "floor(T^0.25)")


def test_g3_all_four_none_vs_signal_cells():
    class _Concept:
        def __init__(self, v): self.value = v

    class _Sig:
        def __init__(self, v):
            self.concept_id = _Concept(v)
            self.parameters = {}

    k = FieldKey("control_axis")
    assert compare_field(k, None, None).equal is True
    assert compare_field(k, None, "var_5pct").equal is False        # fabrication
    assert compare_field(k, _Sig("credit_rating"), None).equal is False
    assert compare_field(k, _Sig("credit_rating"), "credit_rating").equal is True
    assert compare_field(k, _Sig("credit_rating"), "var_5pct").equal is False


def test_g3_prose_fields_have_no_policy():
    for name in ("method_summary", "universe_filter"):
        out = compare_field(FieldKey(name), "some gold prose", "some run prose")
        assert out.comparability is Comparability.NO_POLICY
        assert out.equal is None


def test_g3_paper_metric_compares_as_a_mapping():
    m = {"mean": 0.7, "t_stat": 3.6, "unit": "pct_per_month"}
    assert compare_field(FieldKey("claimed_headline_metric"), m, dict(m)).equal is True
    assert compare_field(FieldKey("claimed_headline_metric"), m,
                         {"mean": 0.7, "t_stat": 3.9, "unit": "pct_per_month"}).equal is False


def test_g3_parameterised_gold_concept_is_declared_not_scorable():
    """D34 wants concept + canonical parameters. The run's parameters live in
    separate trace records and are not joined yet, so a parameterised gold
    concept must NOT be scored on concept alone -- that would report a match
    nothing checked."""
    class _Concept:
        def __init__(self, v): self.value = v

    class _Sig:
        def __init__(self, v, p):
            self.concept_id = _Concept(v)
            self.parameters = p

    out = compare_field(FieldKey("sort_signal"), _Sig("var_5pct", {"window": 36}), "var_5pct")
    assert out.comparability is Comparability.NO_POLICY
    assert out.equal is None


